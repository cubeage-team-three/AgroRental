package com.agrorental.booking;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.condition.EnabledIf;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.flyway.autoconfigure.FlywayMigrationStrategy;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Import;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.TestPropertySource;

import java.net.Socket;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Runs the BIZ-13/14/20 scenarios against a disposable MySQL 8 on localhost:33306 whose schema is built by the
 * real Flyway migrations (V1, V1.1, V2) and validated by Hibernate, rather than generated by Hibernate. This proves
 * the refund tables from V2 match the entities and that the refund locking/constraints hold on the migrated schema.
 * Uses its own throwaway schema, cleaned and migrated at context start. Skipped when that server is absent.
 */
@EnabledIf("isDisposableMysqlRunning")
// Intentional local MySQL run: the profile must be explicit (StartupSafetyValidator)
@ActiveProfiles("dev")
@TestPropertySource(properties = {
    "spring.datasource.url=jdbc:mysql://127.0.0.1:33306/agrorental_refund_flyway_test?createDatabaseIfNotExist=true&useSSL=false&allowPublicKeyRetrieval=true",
    "spring.datasource.username=root",
    "spring.datasource.password=root",
    "spring.datasource.driver-class-name=com.mysql.cj.jdbc.Driver",
    "spring.datasource.hikari.maximum-pool-size=20",
    "spring.jpa.hibernate.ddl-auto=validate",
    "spring.flyway.enabled=true",
    "spring.flyway.locations=classpath:db/migration",
    // Only this throwaway test schema is ever cleaned
    "spring.flyway.clean-disabled=false",
    "agrorental.seed.mock-data.enabled=false",
    "app.jwt.secret=test-secret-key-32-chars-minimum-length-for-hmac-sha256",
    "server.port=0"
})
@Import(BookingPaymentIntegrityMySQLFlywayTest.CleanThenMigrate.class)
@DisplayName("BIZ-13/14/20: Booking and payment integrity (disposable MySQL 8, Flyway-migrated schema)")
class BookingPaymentIntegrityMySQLFlywayTest extends AbstractBookingPaymentIntegrityTest {

    static boolean isDisposableMysqlRunning() {
        try (Socket socket = new Socket("127.0.0.1", 33306)) {
            return true;
        } catch (Exception e) {
            return false;
        }
    }

    @TestConfiguration
    static class CleanThenMigrate {
        @Bean
        FlywayMigrationStrategy cleanThenMigrate() {
            return flyway -> {
                flyway.clean();
                flyway.migrate();
            };
        }
    }

    @Autowired
    private Flyway flyway;

    @Test
    void schemaWasBuiltByTheRefundMigration() {
        assertThat(flyway.info().current().getVersion().getVersion()).isEqualTo("3");
        assertThat(flyway.info().applied()).hasSize(4);
    }
}
